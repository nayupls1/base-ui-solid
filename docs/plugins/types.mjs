import fs from 'node:fs/promises';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkGfm from 'remark-gfm';
import { toString } from 'mdast-util-to-string';
import { highlightToHtml } from './highlight.mjs';
import { solidifyPropName, solidifyText, solidifyType } from './solidify.mjs';
import { renderMarkdownInline, renderMarkdown } from './markdown.mjs';

const processor = unified().use(remarkParse).use(remarkGfm);

function cellSource(markdown, cell) {
  return markdown
    .slice(cell.position.start.offset, cell.position.end.offset)
    .replace(/^\|/, '')
    .trim();
}

function cleanCell(text) {
  return text.replace(/&#xA;/g, '\n').replace(/\\\|/g, '|').trim();
}

function stripCode(text) {
  const match = text.match(/^`(.*)`$/s);
  return match ? match[1] : text;
}

async function parseTable(markdown, node) {
  const [header, ...rows] = node.children;
  const headers = header.children.map((cell) => toString(cell).trim().toLowerCase());
  const result = [];
  for (const row of rows) {
    const entry = {};
    row.children.forEach((cell, index) => {
      const raw = cell.position
        ? markdown.slice(cell.position.start.offset, cell.position.end.offset).trim()
        : toString(cell);
      entry[headers[index]] = cleanCell(raw.replace(/^\|/, '').replace(/\|$/, ''));
    });
    result.push(entry);
  }
  return result;
}

/**
 * Parses an autogenerated Base UI `types.md` into reference data, translated to Solid.
 */
export async function parseTypesMarkdown(markdown) {
  const tree = processor.parse(markdown);
  const parts = {};
  const order = [];
  let current = null;
  let pendingLabel = null;

  for (const node of tree.children) {
    if (node.type === 'heading' && node.depth === 3) {
      const name = toString(node).trim();
      current = {
        name,
        description: [],
        props: null,
        dataAttributes: null,
        cssVariables: null,
        examples: {},
        sections: [],
      };
      parts[name] = current;
      order.push(name);
      pendingLabel = null;
      continue;
    }
    if (!current) {
      continue;
    }

    const source = markdown.slice(node.position.start.offset, node.position.end.offset);

    if (node.type === 'paragraph' && /^\*\*.*:\*\*$/.test(source.trim())) {
      pendingLabel = source.trim().replace(/^\*\*|:\*\*$/g, '');
      continue;
    }

    if (node.type === 'table' && pendingLabel) {
      const rows = await parseTable(markdown, node);
      if (/ Props$/.test(pendingLabel)) {
        current.props = rows;
      } else if (/Data Attributes$/.test(pendingLabel)) {
        current.dataAttributes = rows;
      } else if (/CSS Variables$/.test(pendingLabel)) {
        current.cssVariables = rows;
      } else {
        current.sections.push({ label: pendingLabel, markdown: source });
      }
      pendingLabel = null;
      continue;
    }

    if (pendingLabel) {
      const exampleMatch = pendingLabel.match(/^`(\w+)` Prop Example$/);
      if (exampleMatch) {
        current.examples[solidifyPropName(exampleMatch[1])] = source;
        pendingLabel = null;
        continue;
      }
      current.sections.push({ label: pendingLabel, markdown: source });
      pendingLabel = pendingLabel === 'Methods' ? pendingLabel : null;
      continue;
    }

    current.description.push(source);
  }

  const output = {};
  for (const name of order) {
    const part = parts[name];
    const rendered = {
      name,
      description: part.description.length
        ? await renderMarkdown(solidifyText(part.description.join('\n\n')))
        : '',
      props: null,
      dataAttributes: null,
      cssVariables: null,
      sections: [],
    };

    if (part.props) {
      rendered.props = [];
      for (const row of part.props) {
        const propName = solidifyPropName(row.prop);
        let type = solidifyType(stripCode(row.type ?? ''));
        if (propName === 'class') {
          type = type.replace(/^string \|/, 'ClassValue |');
        }
        const defaultValue = row.default && row.default !== '-' ? stripCode(row.default) : null;
        rendered.props.push({
          name: propName,
          type,
          typeHtml: type ? await highlightToHtml(type, 'ts') : '',
          default: defaultValue,
          defaultHtml: defaultValue ? await highlightToHtml(defaultValue, 'ts') : '',
          description: row.description
            ? await renderMarkdown(solidifyText(row.description))
            : '',
          example: part.examples[propName]
            ? await renderMarkdown(solidifyText(part.examples[propName]))
            : '',
        });
      }
    }

    if (part.dataAttributes) {
      rendered.dataAttributes = [];
      for (const row of part.dataAttributes) {
        const type = row.type && row.type !== '-' ? stripCode(row.type) : null;
        rendered.dataAttributes.push({
          name: row.attribute,
          type,
          typeHtml: type ? await highlightToHtml(type, 'ts') : '',
          description: await renderMarkdownInline(solidifyText(row.description ?? '')),
        });
      }
    }

    if (part.cssVariables) {
      rendered.cssVariables = [];
      for (const row of part.cssVariables) {
        const type = row.type && row.type !== '-' ? stripCode(row.type) : null;
        rendered.cssVariables.push({
          name: stripCode(row.variable),
          type,
          typeHtml: type ? await highlightToHtml(type, 'ts') : '',
          description: await renderMarkdownInline(solidifyText(row.description ?? '')),
        });
      }
    }

    for (const section of part.sections) {
      rendered.sections.push({
        label: section.label,
        html: await renderMarkdown(solidifyType(solidifyText(section.markdown))),
      });
    }

    output[name] = rendered;
  }

  return output;
}

export function typesPlugin() {
  return {
    name: 'base-ui-solid-types',
    enforce: 'pre',
    async load(id) {
      if (!id.endsWith('.md?types')) {
        return null;
      }
      const file = id.slice(0, -'?types'.length);
      this.addWatchFile(file);
      const markdown = await fs.readFile(file, 'utf8');
      const data = await parseTypesMarkdown(markdown);
      return `export default ${JSON.stringify(data)};`;
    },
  };
}
